/** O'zbekcha ko'rsatish uchun yangi alifbo (Oʻ→Ö, Gʻ→Ğ, Sh→Ş, Ch→Ç) */
export const toNewLatinName = (v: string) =>
  v
    .replace(/O['ʻ‘’`]/g, 'Ö')
    .replace(/o['ʻ‘’`]/g, 'ö')
    .replace(/G['ʻ‘’`]/g, 'Ğ')
    .replace(/g['ʻ‘’`]/g, 'ğ')
    .replace(/S[Hh]/g, 'Ş')
    .replace(/sh/g, 'ş')
    .replace(/C[Hh]/g, 'Ç')
    .replace(/ch/g, 'ç');
